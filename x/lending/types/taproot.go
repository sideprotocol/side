const (
	HASH_TO_CURVE_DOMAIN = "side.lending.vault"
)

// Branch 1: multisig script for borrower and dcm
func CreateMultisigScript(pubKeys [][]byte) ([]byte, error) {
	builder := txscript.NewScriptBuilder()

	for i, pubKey := range pubKeys {
		builder.AddData(pubKey)

		if i == 0 {
			builder.AddOp(txscript.OP_CHECKSIG)
		} else {
			builder.AddOp(txscript.OP_CHECKSIGADD)
		}
	}

	builder.AddInt64(int64(len(pubKeys)))
	builder.AddOp(txscript.OP_NUMEQUAL)

	return builder.Script()
}

// Branch 2: PubKey with time lock script for borrower refund
func CreatePubKeyTimeLockScript(pubKey []byte, lockTime int64) ([]byte, error) {
	builder := txscript.NewScriptBuilder()

	builder.AddInt64(lockTime)
	builder.AddOp(txscript.OP_CHECKLOCKTIMEVERIFY)
	builder.AddOp(txscript.OP_DROP)
	builder.AddData(pubKey)
	builder.AddOp(txscript.OP_CHECKSIG)

	return builder.Script()
}

// Create Taproot address with complex script branches
func CreateTaprootAddress(internalKey *secp256k1.PublicKey, branches [][]byte, params *chaincfg.Params) (string, error) {
	tapScriptTree := GetTapscriptTree(branches)
	scriptRoot := tapScriptTree.RootNode.TapHash()

	taprootOutKey := txscript.ComputeTaprootOutputKey(internalKey, scriptRoot[:])

	// Generate Taproot address
	address, err := btcutil.NewAddressTaproot(schnorr.SerializePubKey(taprootOutKey), params)
	if err != nil {
		return "", err
	}

	return address.EncodeAddress(), nil
}

func CreateVaultAddress(borrowerPubKey string, dcmPubKey string, finalTimeout int64) (string, error) {
	borrowerPubKeyBytes, err := hex.DecodeString(borrowerPubKey)
	if err != nil || len(borrowerPubKeyBytes) != schnorr.PubKeyBytesLen {
		return "", errorsmod.Wrap(ErrInvalidPubKey, "invalid borrower pub key")
	}

	dcmPubKeyBytes, err := hex.DecodeString(dcmPubKey)
	if err != nil || len(dcmPubKeyBytes) != schnorr.PubKeyBytesLen {
		return "", errorsmod.Wrap(ErrInvalidPubKey, "invalid dcm pub key")
	}

	// multisig script
	multisigScript, err := CreateMultisigScript([][]byte{borrowerPubKeyBytes, dcmPubKeyBytes})
	if err != nil {
		return "", err
	}

	// refund script
	timeoutRefundScript, err := CreatePubKeyTimeLockScript(borrowerPubKeyBytes, finalTimeout)
	if err != nil {
		return "", err
	}

	// Combine branches
	branches := [][]byte{multisigScript, timeoutRefundScript}

	// Generate Taproot address
	taprootAddress, err := CreateTaprootAddress(GetInternalKey(borrowerPubKeyBytes, dcmPubKeyBytes), branches, bitcoin.Network)
	if err != nil {
		return "", err
	}

	return taprootAddress, nil
}

// GetInternalKey gets the pub key used for taproot address generation
// Generated by borrower pk + dcm pk, fallback to hashToCurve("side.lending.vault" || borrower pk || dcm pk)
// Assume that the given pub keys are valid
func GetInternalKey(borrowerPubKey []byte, dcmPubKey []byte) *btcec.PublicKey {
	borrowerPk, _ := btcec.ParsePubKey(borrowerPubKey)
	dcmPk, _ := btcec.ParsePubKey(dcmPubKey)

	// P = borrower pk + dcm pk
	var BPK, DPK, P btcec.JacobianPoint
	borrowerPk.AsJacobian(&BPK)
	dcmPk.AsJacobian(&DPK)
	btcec.AddNonConst(&BPK, &DPK, &P)

	// check if P is the point at infinity
	if (P.X.IsZero() && P.Y.IsZero()) || P.Z.IsZero() {
		return hashToCurve(append(borrowerPubKey, dcmPubKey...), HASH_TO_CURVE_DOMAIN)
	}

	P.ToAffine()

	return btcec.NewPublicKey(&P.X, &P.Y)
}

func GetTapscriptTree(scripts [][]byte) *txscript.IndexedTapScriptTree {
	leaves := []txscript.TapLeaf{}

	for _, script := range scripts {
		leaves = append(leaves, txscript.NewBaseTapLeaf(script))
	}

	tree := txscript.AssembleTaprootScriptTree(leaves...)

	return tree
}

func GetControlBlock(pubKey *secp256k1.PublicKey, proof txscript.TapscriptProof) ([]byte, error) {
	controlBlock := proof.ToControlBlock(pubKey)

	controlBlockBz, err := controlBlock.ToBytes()
	if err != nil {
		return nil, err
	}

	return controlBlockBz, nil
}

// CalcTapscriptSigHash computes the sig hash of the given script
// Assume that the psbt is valid
func CalcTapscriptSigHash(p *psbt.Packet, idx int, sigHashType txscript.SigHashType, script []byte) ([]byte, error) {
	prevOutFetcher := txscript.NewMultiPrevOutFetcher(nil)
	for i, txIn := range p.UnsignedTx.TxIn {
		prevOutFetcher.AddPrevOut(txIn.PreviousOutPoint, p.Inputs[i].WitnessUtxo)
	}

	sigHash, err := txscript.CalcTapscriptSignaturehash(txscript.NewTxSigHashes(p.UnsignedTx, prevOutFetcher), sigHashType, p.UnsignedTx, idx, prevOutFetcher, txscript.NewBaseTapLeaf(script))
	if err != nil {
		return nil, err
	}

	return sigHash, nil
}

// GetPkScriptFromAddress gets the pk script of the given address
func GetPkScriptFromAddress(address string) ([]byte, error) {
	addr, err := btcutil.DecodeAddress(address, bitcoin.Network)
	if err != nil {
		return nil, err
	}

	return txscript.PayToAddrScript(addr)
}

// GetPkScriptFromPubKey gets the pk script from the given taproot pubkey
// Assume that the given pubkey is 32 bytes w/o 0x prefix
func GetPkScriptFromPubKey(pubKeyHex string) ([]byte, error) {
	pubKey, err := hex.DecodeString(fmt.Sprintf("02%s", pubKeyHex))
	if err != nil {
		return nil, err
	}

	parsedPubKey, err := secp256k1.ParsePubKey(pubKey)
	if err != nil {
		return nil, err
	}

	taprootOutKey := txscript.ComputeTaprootKeyNoScript(parsedPubKey)

	return txscript.PayToTaprootScript(taprootOutKey)
}

// hashToCurve gets the curve point from the given input and domain
func hashToCurve(input []byte, domain string) *btcec.PublicKey {
	p := h2c.HashToCurve([]byte(input), []byte(domain))

	var X, Y btcec.FieldVal
	X.SetByteSlice(p.X.Bytes())
	Y.SetByteSlice(p.Y.Bytes())

	return btcec.NewPublicKey(&X, &Y)
}
